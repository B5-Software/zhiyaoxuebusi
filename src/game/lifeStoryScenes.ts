export function chapterPresentation(g: GameState, arc: LifeArc, step: number) {
  const chapter = arc.chapters[step], extra = SCENES[arc.id]?.[step];
  const previous = g.life.stories.routes[arc.id]?.choices[step - 1];
  const before = previous === undefined || step === 0 ? null : arc.chapters[step - 1];
  const carry = before && previous !== undefined ? { choice: before.choices[previous], text: before.results[previous] } : null;
  const followUp = previous === undefined ? '' : FOLLOW_UPS[arc.id]?.[step - 1]?.[previous] ?? '';
  const reply = REPLIES[arc.id]?.[step];
  return { paragraphs: [...chapter.paragraphs, ...(extra ? [extra[0]] : []), ...(followUp ? [followUp] : [])], dialogue: [...chapter.dialogue, ...(extra ? [{ speaker: extra[1], text: extra[2] }] : []), ...(reply ? [{speaker:'你',text:reply}] : [])], carry, followUp };
}

